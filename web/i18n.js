  function currentLang() {
    try {
      var stored = localStorage.getItem("pdfforge_lang");
      if (stored) return stored;
    } catch (e) { /* private mode */ }
    return (window.state && window.state.lang) || "id";
  }

  function translate(text, vars) {
    var out = text;
    if (currentLang() === "en") {
      out = Object.prototype.hasOwnProperty.call(DICT, text) ? DICT[text] : text;
    }
    if (vars) {
      Object.keys(vars).forEach(function (key) {
        out = out.split("{" + key + "}").join(String(vars[key]));
      });
    }
    return out;
  }

  function applyStatic(root) {
    var scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = translate(node.dataset.i18n);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
      node.placeholder = translate(node.dataset.i18nPlaceholder);
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach(function (node) {
      node.setAttribute("aria-label", translate(node.dataset.i18nAria));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (node) {
      node.title = translate(node.dataset.i18nTitle);
    });
  }

